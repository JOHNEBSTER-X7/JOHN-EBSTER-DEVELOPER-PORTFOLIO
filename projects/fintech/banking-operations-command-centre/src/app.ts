import express from "express";
import path from "node:path";
import {z} from "zod";
import {CommandCentreService} from "./service";
export const app=express();
export const service=new CommandCentreService();
app.use(express.json({limit:"128kb"}));
app.use(express.static(path.join(process.cwd(),"public")));
const wrap=(fn:(req:express.Request,res:express.Response)=>unknown)=>(req:express.Request,res:express.Response)=>{try{fn(req,res);}catch(e){res.status(400).json({error:e instanceof Error?e.message:"Request failed"});}};
app.get("/api/health",(_req,res)=>res.json({status:"ok",service:"northstar-banking-command-centre",mode:"synthetic-demo"}));
app.get("/api/dashboard",(_req,res)=>res.json(service.dashboard()));
app.get("/api/payments",(_req,res)=>res.json(service.payments));
app.get("/api/alerts",(_req,res)=>res.json(service.alerts));
app.get("/api/alerts/:id",wrap((req,res)=>res.json(service.getAlert(String(req.params.id)))));
app.post("/api/alerts/:id/actions",wrap((req,res)=>{const b=z.object({action:z.enum(["acknowledge","investigate","escalate","resolve"]),actor:z.string().min(2),note:z.string().optional()}).parse(req.body);res.json(service.updateAlert(String(req.params.id),b.action,b.actor,b.note));}));
app.get("/api/work-items",(_req,res)=>res.json(service.workItems));
app.post("/api/work-items/:id/status",wrap((req,res)=>{const b=z.object({status:z.enum(["in_progress","blocked","completed"]),actor:z.string().min(2),note:z.string().optional()}).parse(req.body);res.json(service.updateWorkItem(String(req.params.id),b.status,b.actor,b.note));}));
app.get("/api/activity",(_req,res)=>res.json(service.activity()));
app.get("/api/audit",(_req,res)=>res.json(service.audit));
app.get("/api/liquidity",(_req,res)=>res.json(service.dashboard().liquidity));
